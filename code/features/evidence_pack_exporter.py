"""
GhostTrace AI - Immutable Audit Evidence Pack Exporter
Generates tamper-evident audit export packages with cryptographic SHA-256 evidence digests.
"""

import json
import hashlib
from pathlib import Path
from datetime import datetime, timezone
from typing import Dict, List, Any


class EvidencePackExporter:
    """
    Exports self-contained, tamper-evident audit packages for legal compliance,
    internal audit review, and regulatory defense.
    """

    def __init__(self, dataset_dir: Path):
        self.dataset_dir = dataset_dir
        self.evidence_dir = dataset_dir / "evidence"

    def compute_file_hash(self, file_path: Path) -> str:
        """Calculate SHA-256 digest of an evidence file."""
        if not file_path.exists():
            return "FILE_NOT_FOUND"
        h = hashlib.sha256()
        with open(file_path, "rb") as f:
            while chunk := f.read(65536):
                h.update(chunk)
        return h.hexdigest()

    def generate_pack(self, case_id: str, status: str, steps: List[Dict[str, Any]], user_meta: Dict[str, Any] = None) -> Dict[str, Any]:
        """
        Build an immutable evidence pack dictionary.
        """
        evidence_ids = sorted(list({s.get("evidence_id") for s in steps if s.get("evidence_id")}))
        evidence_manifest = {}

        for eid in evidence_ids:
            matches = list(self.evidence_dir.glob(f"{eid}.*"))
            if matches:
                target = matches[0]
                evidence_manifest[eid] = {
                    "filename": target.name,
                    "sha256": self.compute_file_hash(target),
                    "size_bytes": target.stat().st_size
                }
            else:
                evidence_manifest[eid] = {
                    "filename": f"{eid} (unknown format)",
                    "sha256": "UNKNOWN",
                    "size_bytes": 0
                }

        pack = {
            "pack_version": "1.0-ghosttrace",
            "case_id": case_id,
            "audit_timestamp_utc": datetime.now(timezone.utc).isoformat(),
            "target_organization": "Northstar Shop E-Commerce Platform",
            "auditor_agent": "GhostTrace AI - Deletion Assurance Engine",
            "deletion_status": status,
            "user_identity": user_meta or {},
            "audit_steps": steps,
            "evidence_manifest": evidence_manifest,
            "step_count": len(steps),
            "evidence_count": len(evidence_ids)
        }

        # Seal with composite manifest hash
        serialized = json.dumps(pack, sort_keys=True)
        seal_hash = hashlib.sha256(serialized.encode("utf-8")).hexdigest()
        pack["tamper_evident_seal_sha256"] = seal_hash

        return pack

    def export_markdown(self, pack: Dict[str, Any]) -> str:
        """Render evidence pack as human-readable Markdown report."""
        md = []
        md.append(f"# GhostTrace AI - Immutable Audit Evidence Pack: {pack['case_id']}")
        md.append(f"**Target System:** {pack['target_organization']}")
        md.append(f"**Audit Timestamp:** `{pack['audit_timestamp_utc']}`")
        md.append(f"**Audit Verdict:** **{pack['deletion_status']}**")
        md.append(f"**Integrity Seal (SHA-256):** `{pack['tamper_evident_seal_sha256']}`\n")

        md.append("## Evidence Files Manifest")
        md.append("| Evidence ID | File | Size (Bytes) | SHA-256 Hash |")
        md.append("|---|---|---|---|")
        for eid, m in pack["evidence_manifest"].items():
            md.append(f"| `{eid}` | `{m['filename']}` | {m['size_bytes']} | `{m['sha256'][:16]}...` |")

        md.append("\n## Audit Trail Steps")
        md.append("| Step | Phase | System ID | Resource ID | Operation | State | Evidence |")
        md.append("|---|---|---|---|---|---|---|")
        for s in pack["audit_steps"]:
            md.append(f"| {s['step_no']} | {s['phase']} | `{s['system_id']}` | `{s['resource_id']}` | {s['operation']} | {s['state']} | `{s['evidence_id']}` |")

        md.append("\n---\n*Generated by GhostTrace AI Verification Engine*")
        return "\n".join(md)
